import assert from 'node:assert/strict';
import { after, beforeEach, test } from 'node:test';
import jwt from 'jsonwebtoken';
import { JWT_KEY, PASSWORD, api, db, get, post, resetData, shutdown } from './helpers.js';

const { verifyPassword } = await import('../src/lib/password.js');

beforeEach(resetData);
after(shutdown);

const sign = (claims, options = {}) => jwt.sign(claims, options.key ?? JWT_KEY, {
  algorithm: 'HS256', issuer: 'UserBackend', audience: 'UserFrontend', expiresIn: 3600, noTimestamp: true, ...options.sign,
});

test('login returns a token and the profile with exact money values', async () => {
  const res = await post('/api/auth/login', { loginId: 'user', password: PASSWORD });
  assert.equal(res.status, 200);
  assert.match(res.text, /"user":\{"uid":\d+,"name":"user","loginId":"user","balance":1000\.00,"point":250\.00,"status":"Active"\}\}$/);
  assert.equal(res.json.user.balance, 1000);

  const claims = jwt.verify(res.json.token, JWT_KEY, { issuer: 'UserBackend', audience: 'UserFrontend' });
  assert.deepEqual(Object.keys(claims).sort(), ['aud', 'exp', 'iss', 'jti', 'name', 'sub', 'unique_name']);
  assert.equal(claims.sub, String(res.json.user.uid));
  assert.equal(claims.unique_name, 'user');
  assert.equal(claims.name, 'user');
  assert.ok(Math.abs(claims.exp - (Date.now() / 1000 + 12 * 3600)) < 60, 'expires in 12 hours');
});

