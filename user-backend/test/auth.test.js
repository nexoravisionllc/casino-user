test('login id comparison is case-insensitive, password is not', async () => {
  assert.equal((await post('/api/auth/login', { loginId: 'USER', password: PASSWORD })).status, 200);
  assert.equal((await post('/api/auth/login', { loginId: 'user', password: PASSWORD.toUpperCase() + 'x' })).status, 401);
});

test('login failures keep their status and message', async () => {
  const cases = [
    [{ loginId: 'nobody', password: PASSWORD }, 401, 'Invalid login id or password.'],
    [{ loginId: 'user', password: 'wrong' }, 401, 'Invalid login id or password.'],
    [{ loginId: 'pending1', password: PASSWORD }, 401, 'This account is not active.'],
    [{ loginId: 'blocked', password: PASSWORD }, 401, 'This account is not active.'],
    [{ loginId: '', password: PASSWORD }, 400, 'Login id and password are required.'],
    [{ loginId: 'user', password: '   ' }, 400, 'Login id and password are required.'],
  ];
  for (const [body, status, message] of cases) {
    const res = await post('/api/auth/login', body);
    assert.equal(res.status, status, JSON.stringify(body));
    assert.equal(res.json.message, message, JSON.stringify(body));
  }
});

