test('protected routes enforce the bearer token', async () => {
  const [user] = await db.query("SELECT Uid FROM Users WHERE LoginId = 'user'");
  const good = { sub: String(user.Uid), unique_name: 'user', name: 'user', jti: 'a' };

  const missing = await get('/api/transactions');
  assert.equal(missing.status, 401);
  assert.equal(missing.text, '');
  assert.equal(missing.headers.get('www-authenticate'), 'Bearer');

  assert.equal((await get('/api/transactions', { token: 'garbage' })).status, 401);
  assert.equal((await get('/api/transactions', { token: sign(good, { key: 'x'.repeat(40) }) })).status, 401);
  assert.equal((await get('/api/transactions', { token: sign(good, { sign: { issuer: 'AdminBackend' } }) })).status, 401);
  assert.equal((await get('/api/transactions', { token: sign(good, { sign: { audience: 'AdminFrontend' } }) })).status, 401);
  assert.equal((await get('/api/transactions', { token: sign(good, { sign: { expiresIn: -3600 } }) })).status, 401);

  // A token issued by the C# backend (same claims and key) keeps working.
  assert.equal((await get('/api/transactions', { token: sign(good) })).status, 200);
  // Allowed by ASP.NET's five-minute clock skew.
  assert.equal((await get('/api/transactions', { token: sign(good, { sign: { expiresIn: -120 } }) })).status, 200);
});

test('CORS allows configured origins only', async () => {
  const allowed = await get('/api/games/settings', { headers: { Origin: 'https://allowed.test' } });
  assert.equal(allowed.headers.get('access-control-allow-origin'), 'https://allowed.test');
  assert.equal(allowed.headers.get('access-control-allow-credentials'), 'true');

  const denied = await get('/api/games/settings', { headers: { Origin: 'https://evil.test' } });
  assert.equal(denied.headers.get('access-control-allow-origin'), null);

  const preflight = await api('OPTIONS', '/api/auth/login', {
    headers: { Origin: 'http://localhost:5173', 'Access-Control-Request-Method': 'POST', 'Access-Control-Request-Headers': 'content-type,authorization' },
  });
  assert.ok(preflight.status < 300);
  assert.equal(preflight.headers.get('access-control-allow-origin'), 'http://localhost:5173');
});

