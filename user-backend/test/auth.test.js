test('login rejects malformed requests as ASP.NET model binding did', async () => {
  const noField = await post('/api/auth/login', { password: PASSWORD });
  assert.equal(noField.status, 400);
  assert.equal(noField.json.status, 400);
  assert.ok(noField.json.errors.LoginId);

  assert.equal((await post('/api/auth/login', { loginId: 5, password: PASSWORD })).status, 400);
  assert.equal((await post('/api/auth/login', '{not json')).status, 400);
  assert.equal((await post('/api/auth/login', '[1]')).status, 400);
  assert.equal((await post('/api/auth/login', '')).status, 400);
  assert.equal((await post('/api/auth/login', 'x=1', { headers: { 'Content-Type': 'text/plain' } })).status, 415);
  assert.equal((await api('POST', '/api/auth/login')).status, 415);
});

test('accepts password hashes in the format written by the C# backend', async () => {
  // Generated by the same PBKDF2 parameters as PasswordHasher.cs.
  const salt = Buffer.alloc(16, 7);
  const { pbkdf2Sync } = await import('node:crypto');
  const hash = pbkdf2Sync('legacy-pass', salt, 100000, 32, 'sha256');
  const stored = `100000.${salt.toString('base64')}.${hash.toString('base64')}`;
  assert.equal(await verifyPassword('legacy-pass', stored), true);
  assert.equal(await verifyPassword('other', stored), false);
  assert.equal(await verifyPassword('x', 'not-a-hash'), false);
});

test('registers a pending user under the administrator when the referral is blank', async () => {
  const res = await post('/api/auth/register', {
    name: '  New Person ', loginId: ' newbie ', password: 'secret-1', referralId: null,
    email: 'n@test', bankName: 'B', bankAccount: '123', bankMaster: 'M',
  });
  assert.deepEqual(res.json, { ok: true, message: 'Your sign-up request has been submitted and is pending approval.' });

  const [row] = await db.query(
    `SELECT u.*, p.LoginId AS parent FROM Users u JOIN Partners p ON p.Uid = u.PartnerId WHERE u.LoginId = 'newbie'`);
  assert.equal(row.Name, 'New Person');
  assert.equal(row.parent, 'Admin');
  assert.equal(row.Status, 'Pending');
  assert.equal(row.Balance, '0.00');
  assert.equal(row.Email, 'n@test');
  assert.equal(await verifyPassword('secret-1', row.Password), true);

  const login = await post('/api/auth/login', { loginId: 'newbie', password: 'secret-1' });
  assert.equal(login.status, 401);
  assert.equal(login.json.message, 'This account is not active.');
});

